// Generates public/lwjgl3/generated/natives.js from official LWJGL 3 jars.
// Usage: node scripts/gen-lwjgl-tables.mjs <dir with lwjgl*.jar files>
//
// The browser backend implements LWJGL's native methods in JavaScript (CheerpJ "natives").
// CheerpJ resolves a native by its short JNI name, so this lists, per class, the native
// method names that exist across all LWJGL versions used by Minecraft (3.1.6 - 3.4.x).
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { inflateRawSync } from 'node:zlib';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = process.argv[2];
if (!dir) {
  console.error('usage: node scripts/gen-lwjgl-tables.mjs <dir with lwjgl jars>');
  process.exit(2);
}

function* entries(buffer) {
  let eocd = buffer.length - 22;
  while (eocd >= 0 && buffer.readUInt32LE(eocd) !== 0x06054b50) eocd--;
  const count = buffer.readUInt16LE(eocd + 10);
  let offset = buffer.readUInt32LE(eocd + 16);
  for (let i = 0; i < count; i++) {
    const method = buffer.readUInt16LE(offset + 10);
    const size = buffer.readUInt32LE(offset + 20);
    const nameLength = buffer.readUInt16LE(offset + 28);
    const extra = buffer.readUInt16LE(offset + 30);
    const comment = buffer.readUInt16LE(offset + 32);
    const local = buffer.readUInt32LE(offset + 42);
    const name = buffer.toString('utf8', offset + 46, offset + 46 + nameLength);
    offset += 46 + nameLength + extra + comment;
    if (!name.endsWith('.class')) continue;
    const start = local + 30 + buffer.readUInt16LE(local + 26) + buffer.readUInt16LE(local + 28);
    const data = buffer.subarray(start, start + size);
    yield method === 8 ? inflateRawSync(data) : data;
  }
}

function nativeMethods(bytes) {
  let p = 8;
  const count = bytes.readUInt16BE(p);
  p += 2;
  const utf8 = [];
  const classes = [];
  for (let i = 1; i < count; i++) {
    const tag = bytes[p++];
    if (tag === 1) {
      const length = bytes.readUInt16BE(p);
      utf8[i] = bytes.toString('utf8', p + 2, p + 2 + length);
      p += 2 + length;
    } else if (tag === 7) {
      classes[i] = bytes.readUInt16BE(p);
      p += 2;
    } else if ([8, 16, 19, 20].includes(tag)) p += 2;
    else if (tag === 15) p += 3;
    else if ([3, 4, 9, 10, 11, 12, 17, 18].includes(tag)) p += 4;
    else if (tag === 5 || tag === 6) {
      p += 8;
      i++;
    } else throw new Error(`tag ${tag}`);
  }
  p += 2; // access flags
  const className = utf8[classes[bytes.readUInt16BE(p)]];
  p += 4; // this_class, super_class
  p += 2 + bytes.readUInt16BE(p) * 2; // interfaces
  const members = (collect) => {
    const n = bytes.readUInt16BE(p);
    p += 2;
    const out = [];
    for (let i = 0; i < n; i++) {
      const access = bytes.readUInt16BE(p);
      const name = utf8[bytes.readUInt16BE(p + 2)];
      const attributes = bytes.readUInt16BE(p + 6);
      p += 8;
      for (let a = 0; a < attributes; a++) p += 6 + bytes.readUInt32BE(p + 2);
      if (collect && access & 0x0100) out.push(name);
    }
    return out;
  };
  members(false);
  return { className, natives: members(true) };
}

const byClass = new Map();
for (const file of readdirSync(dir).filter((f) => f.endsWith('.jar') && !f.includes('natives'))) {
  for (const bytes of entries(readFileSync(path.join(dir, file)))) {
    const { className, natives } = nativeMethods(bytes);
    if (!natives.length) continue;
    const set = byClass.get(className) || new Set();
    natives.forEach((n) => set.add(n));
    byClass.set(className, set);
  }
}

const sorted = [...byClass.keys()].sort();
const lines = sorted.map((c) => `  ${JSON.stringify(c)}: ${JSON.stringify([...byClass.get(c)].sort())},`);
const out = path.join(root, 'public', 'lwjgl3', 'generated', 'natives.js');
mkdirSync(path.dirname(out), { recursive: true });
writeFileSync(out, `// Generated by scripts/gen-lwjgl-tables.mjs from the official LWJGL 3 jars. Do not edit.
// Native method names declared by each LWJGL class, across LWJGL 3.1.6 - 3.4.x.
export const LWJGL_NATIVES = {
${lines.join('\n')}
};
`);
const total = sorted.reduce((sum, c) => sum + byClass.get(c).size, 0);
console.log(`${sorted.length} classes, ${total} native methods -> ${path.relative(root, out)}`);
